// 지역명 찾기: 입력 → {name, lon} 또는 null. 시·군 이름이 들어 있으면 그걸, 없으면 도 중심값.
function findPlace(raw){
  const s = String(raw||"").replace(/\s+/g,"").replace(/(특별자치시|특별자치도|특별시|광역시)/g,"");
  if(!s) return null;
  if(s.includes("광주") && s.includes("경기")) return {name:"경기 광주",lon:127.26};
  if(s.includes("고성") && /경남|경상남/.test(s)) return {name:"경남 고성",lon:128.32};
  for(const [n,lon] of PLACE_SORTED) if(s.includes(n)) return {name:n==="고성"?"강원 고성":n,lon};
  for(const [n,lon,full] of PROVINCES) if(s.includes(n)) return {name:full+" (도 중심)",lon};
  return null;
}
